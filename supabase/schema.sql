-- ------------------------------------------------------------ tablas

create table if not exists usuarios (
  email      text primary key,
  nombre     text,
  rol        text not null default 'usuario' check (rol in ('admin', 'usuario')),
  created_at timestamptz not null default now()
);

create table if not exists config (
  id      int primary key default 1 check (id = 1),
  valores jsonb not null default '{}'
);

create table if not exists aseguradoras (
  id         bigint generated by default as identity primary key,
  nombre     text not null unique,
  variantes  text[] not null default '{}',
  web        text,
  portal     text,                       -- link al portal (nunca usuario ni clave)
  contactos  jsonb not null default '[]', -- [{tramite, dato, telefono}] (segunda etapa)
  activa     boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists rubros (
  id        bigint generated by default as identity primary key,
  nombre    text not null unique,
  orden     int not null default 0,
  usa_items boolean not null default false, -- true: la póliza lleva vehículos (patente)
  campos    jsonb not null default '[]',    -- [{k, label, tipo, opciones?}]
  activo    boolean not null default true
);

create table if not exists clientes (
  id            bigint generated by default as identity primary key,
  nombre        text not null,
  doc           text,           -- DNI o CUIT
  mail          text,
  telefono      text,
  domicilio     text,
  observaciones text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  updated_by    text
);
create index if not exists clientes_doc_idx on clientes (doc);

create table if not exists polizas (
  id             bigint generated by default as identity primary key,
  cliente_id     bigint references clientes (id) on delete restrict,
  aseguradora_id bigint references aseguradoras (id) on delete restrict,
  rubro_id       bigint references rubros (id) on delete restrict,
  numero         text,
  detalle        text,
  desde          date,
  vence          date,
  fin_anual      date,          -- Mercantil: fin anual aparte del cierre cuatrimestral
  renovacion     text,          -- Automática / Manual / Cupones (null = sin definir)
  gestion        text default 'Sin gestionar',
  estado_cuota   text,
  prox_vto_cuota date,
  datos          jsonb not null default '{}', -- campos propios del rubro
  notas          text,
  estado         text not null default 'activa' check (estado in ('activa', 'baja')),
  baja_motivo    text,
  baja_fecha     date,
  revisar        text,          -- motivo de "Para completar" (null = está todo)
  renovada_de    bigint references polizas (id) on delete set null,
  origen         text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  updated_by     text
);
create index if not exists polizas_cliente_idx on polizas (cliente_id);
create index if not exists polizas_estado_vence_idx on polizas (estado, vence);

create table if not exists poliza_items (
  id        bigint generated by default as identity primary key,
  poliza_id bigint not null references polizas (id) on delete cascade,
  patente   text,
  detalle   text,
  datos     jsonb not null default '{}'
);
create index if not exists poliza_items_poliza_idx on poliza_items (poliza_id);
create index if not exists poliza_items_patente_idx on poliza_items (patente);

create table if not exists biblioteca (
  id        bigint generated by default as identity primary key,
  categoria text,
  titulo    text not null,
  url       text
);

create table if not exists auditoria (
  id          bigint generated by default as identity primary key,
  tabla       text not null,
  registro_id bigint,
  accion      text not null,
  usuario     text,
  cambios     jsonb,
  fecha       timestamptz not null default now()
);

