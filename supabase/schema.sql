-- Pasa al Histórico las vencidas hace más de N días (config.dias_historico).
-- La llama la app al abrir y la tarea diaria de GitHub (que además evita que
-- Supabase pause el proyecto por inactividad). No devuelve datos personales.
create or replace function mantenimiento() returns int
language plpgsql security definer set search_path = public as $$
declare
  hoy  date := (now() at time zone 'America/Argentina/Cordoba')::date;
  dias int  := coalesce((select (valores ->> 'dias_historico')::int from config where id = 1), 30);
  n    int;
begin
  if dias <= 0 then return 0; end if;
  update polizas
     set estado = 'baja',
         baja_fecha = vence,
         baja_motivo = case when gestion = 'No renueva' then 'No renueva' else 'Vencida sin renovar' end
   where estado = 'activa' and vence is not null and vence < hoy - dias;
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function mantenimiento() from public;
grant execute on function mantenimiento() to anon, authenticated;

-- Después de la carga inicial (que trae ids propios) acomoda los contadores.
create or replace function reiniciar_secuencias() returns void
language plpgsql security definer set search_path = public as $$
declare t text;
begin
  if not es_admin() then raise exception 'Solo un administrador puede hacer esto'; end if;
  foreach t in array array['aseguradoras','rubros','clientes','polizas','poliza_items','biblioteca']
  loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from %I), 0) + 1, false)', t, t);
  end loop;
end $$;
revoke all on function reiniciar_secuencias() from public, anon;
grant execute on function reiniciar_secuencias() to authenticated;

-- Borra toda la cartera (para rehacer la carga inicial). Solo admin.
create or replace function vaciar_cartera() returns void
language plpgsql security definer set search_path = public as $$
begin
  if not es_admin() then raise exception 'Solo un administrador puede hacer esto'; end if;
  truncate poliza_items, siniestros, polizas, clientes, aseguradoras, rubros, biblioteca restart identity cascade;
end $$;
revoke all on function vaciar_cartera() from public, anon;
grant execute on function vaciar_cartera() to authenticated;

