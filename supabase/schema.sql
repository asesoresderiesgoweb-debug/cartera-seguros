-- ------------------------------------------------------------ permisos

-- ¿El usuario logueado está en la lista autorizada?
create or replace function es_usuario() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from usuarios where lower(email) = lower(auth.jwt() ->> 'email'));
$$;

create or replace function es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from usuarios where lower(email) = lower(auth.jwt() ->> 'email') and rol = 'admin');
$$;

do $$
declare t text;
begin
  foreach t in array array['config','aseguradoras','rubros','clientes','polizas','poliza_items',
                           'biblioteca','siniestros','plantillas_mensajes']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "solo usuarios autorizados" on %I', t);
    execute format('create policy "solo usuarios autorizados" on %I for all to authenticated
                    using (es_usuario()) with check (es_usuario())', t);
    execute format('revoke all on %I from anon', t);
  end loop;
end $$;

alter table usuarios enable row level security;
drop policy if exists "ver usuarios" on usuarios;
create policy "ver usuarios" on usuarios for select to authenticated using (es_usuario());
drop policy if exists "admin gestiona usuarios" on usuarios;
create policy "admin gestiona usuarios" on usuarios for all to authenticated using (es_admin()) with check (es_admin());
revoke all on usuarios from anon;

alter table auditoria enable row level security;
drop policy if exists "ver auditoria" on auditoria;
create policy "ver auditoria" on auditoria for select to authenticated using (es_usuario());
revoke all on auditoria from anon;

-- ------------------------------------------------------------ triggers

create or replace function marcar_cambio() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'UPDATE' then
    new.updated_at := now();
    new.updated_by := auth.jwt() ->> 'email';
  end if;
  insert into auditoria (tabla, registro_id, accion, usuario, cambios)
  values (tg_table_name, coalesce(new.id, old.id), lower(tg_op), auth.jwt() ->> 'email',
          case when tg_op = 'UPDATE' then
            (select jsonb_object_agg(n.key, n.value) from jsonb_each(to_jsonb(new)) n
              where n.key not in ('updated_at', 'updated_by') and to_jsonb(old) -> n.key is distinct from n.value)
          when tg_op = 'DELETE' then to_jsonb(old) else null end);
  return coalesce(new, old);
end $$;

drop trigger if exists polizas_cambio on polizas;
create trigger polizas_cambio before update on polizas for each row execute function marcar_cambio();
drop trigger if exists polizas_baja on polizas;
create trigger polizas_baja after delete on polizas for each row execute function marcar_cambio();
drop trigger if exists clientes_cambio on clientes;
create trigger clientes_cambio before update on clientes for each row execute function marcar_cambio();

